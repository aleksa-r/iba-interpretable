"""Tables of the paper's results section and appendix, from the stored forecasts and reports (nothing is refitted).

  .venv/bin/python scripts/make_paper_tables.py     # writes paper/results_tables.md

Development and confirmation numbers are computed by the same code: all series of a frequency pooled on the same
dates, relative difference in the primary loss, 95 % date-block bootstrap per task. Entry format:
"mean over the tasks of the type (tasks significantly better / worse of n)"."""
import glob, importlib.util, json, os, pickle, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
import numpy as np, pandas as pd
from iba.protocol import study

HERE = os.path.dirname(os.path.abspath(__file__))
_s = importlib.util.spec_from_file_location("make_extra_metrics", os.path.join(HERE, "make_extra_metrics.py"))
em = importlib.util.module_from_spec(_s); _s.loader.exec_module(em)
wr = em.wr
KINDS = [("return", "Return"), ("logrv", "Volatility"), ("tail_loss", "Large loss"), ("tail_gain", "Large gain")]
FIXED, ACC = "Kc|lin", "iba_ca_b"
METHODS = [("IBA, interpretable reading", FIXED), ("IBA, accuracy reading", ACC), ("IBA, generic formulas", "G|lin"), ("IBA, random formulas", "Rm"),
           ("Group PCA", "gpca|lin"), ("PCA", "pca|lin"), ("LASSO", "lasso|lin"), ("Raw factors", "raw|lin"), ("Kernel PCA", "kpca|lin"), ("Autoencoder", "ae|lin"),
           ("Time-series momentum", "bench|tsmom"), ("GARCH(1,1)", "bench|garch"), ("GJR-GARCH", "bench|gjr"), ("Volatility logit", "bench|logit_vol"),
           ("GARCH probability", "bench|garch_prob")]
RES = lambda *p: os.path.join(wr.REPO, "docs", "results", *p)


def development():
    by = wr.load()
    cell = lambda spec, stage, *mid: (lambda t: os.path.join(wr.REPO, "artifacts", spec, f"stage{stage}", *mid, t.frequency, t.name, t.target.replace("^", "_"), "predictions.csv"))
    em.add_columns(by, cell(study.FIRST_SPEC, 1), lambda c: c.split("::")[0] in em.GARCH)
    em.add_columns(by, cell(study.BENCH2, 10), lambda c: c.startswith(("kpca|", "ae|")))
    em.add_columns(by, cell(study.WRAPUP, 9, "prior_Kc"), lambda c: c.split("::")[0].startswith("iba_ca"))
    return by


def confirmation():
    tasks = study.confirmation_tasks()
    if not os.path.exists(RES(study.CONFIRM, "claims.csv")):          # only after the pre-written report of the run has decided the claims
        return None
    return wr.load(stage=11, sets=study.STAGES[11]["priors"], spec=study.CONFIRM, task_list=tasks)


def confirmation_hf():
    """The hedge-fund confirmation run (BarclayHedge indices), once its pre-written report has decided the claims."""
    if not os.path.exists(RES(study.CONFIRM_HF, "claims.csv")):
        return None
    return wr.load(stage=12, sets=study.STAGES[12]["priors"], spec=study.CONFIRM_HF, task_list=study.hf_confirmation_tasks())


def tests(by):
    pairs = [(c, "REF") for _, c in METHODS] + [(a, c) for a in (FIXED, ACC) for _, c in METHODS[2:10]] + [(ACC, FIXED), (ACC, "Kc_nb")]
    pairs += [(f"{x}|{e}", f"{x}|lin") for x in ("Kc", "raw", "gpca") for e in ("xgb", "gbt")]
    P, _ = wr.paired(by, list(dict.fromkeys(pairs)), spread_table=False, skip_missing=True)
    return P


def entry(P, a, b, kind, freq=None):
    g = P[(P.a == a) & (P.b == b) & (P.kind == kind)]
    if freq:
        g = g[g.frequency == freq]
    if g.empty:
        return "–"
    return f"{100 * g.rel_diff.mean():+.1f} % ({int((g.verdict == 'better').sum())}/{int((g.verdict == 'worse').sum())} of {len(g)})"


def md_table(rows, cols):
    return pd.DataFrame(rows, columns=cols).to_markdown(index=False)


def main():
    out = ["# Result tables for the paper (generated by scripts/make_paper_tables.py)", "",
           "Entry: mean relative difference in the primary loss over the tasks of the type, a minus b (negative = a better); in brackets the tasks in which the "
           "95 % interval excludes zero in favour of a / against a. Development: 37 weekly and 11 monthly series. Confirmation: 21 weekly series.", ""]
    Pd = tests(development())
    bc = confirmation()
    Pc = tests(bc) if bc is not None else None
    samples = [("Development, weekly", Pd, "weekly"), ("Development, monthly", Pd, "monthly")] + ([("Confirmation, weekly", Pc, "weekly")] if Pc is not None else [])
    bh = confirmation_hf()
    Ph = tests(bh) if bh is not None else None
    if Ph is not None:
        samples.append(("Confirmation, monthly hedge-fund indices of a second provider", Ph, "monthly"))

    # ---- Table 9: the claims
    cl = RES(study.CONFIRM, "claims.csv")
    if os.path.exists(cl):
        C = pd.read_csv(cl).fillna("")
        # wording only: internal names of tasks and configurations spelled out; the csv stays as the run wrote it
        words = [(r"tail_gain_q10_h(\d+)", r"large gain, \1 weeks"), (r"\bKc\+", "IBA + "), (r"\braw\+", "raw factors + "),
                 (r"\bgpca\+", "group PCA + "), (r"\+ xgb\b", "+ XGBoost"), (r"\+ gbt\b", "+ LightGBM"), (r"p = 0\.000\b", "p < 0.001")]
        for col in C.columns:
            for a, b in words:
                C[col] = C[col].astype(str).str.replace(a, b, regex=True)
        out += ["## Table 9. Claims fixed before the confirmation run and their decisions", "", C.to_markdown(index=False), ""]

    # ---- Table 9-HF: the claims of the hedge-fund confirmation
    clh = RES(study.CONFIRM_HF, "claims.csv")
    if os.path.exists(clh):
        C = pd.read_csv(clh).fillna("")
        for col in C.columns:
            for a, b in ((r"tail_(gain|loss)_q10_h(\d+)", r"large \1, \2 months"), (r"return_h(\d+)", r"return, \1 months"), (r"\bKc\|lin\b", "IBA interpretable"),
                         (r"\biba_ca_b\b", "IBA accuracy"), (r"\bKc\+", "IBA + "), (r"\braw\+", "raw factors + "), (r"\bgpca\+", "group PCA + "),
                         (r"\+ xgb\b", "+ XGBoost"), (r"\+ gbt\b", "+ LightGBM"), (r"\b(\w+)\|lin\b", r"\1")):
                C[col] = C[col].astype(str).str.replace(a, b, regex=True)
        out += ["## Table 9-HF. Claims of the hedge-fund confirmation run and their decisions", "", C.to_markdown(index=False), ""]

    # ---- Table 10: every method against the reference
    out += ["## Table 10. Loss relative to the reference of each target (historical mean / HAR / base rate)", ""]
    for name, P, freq in samples:
        rows = [[lab] + [entry(P, c, "REF", k, freq) for k, _ in KINDS] for lab, c in METHODS]
        rows = [r for r in rows if any(x != "–" for x in r[1:])]
        out += [f"**{name}**", "", md_table(rows, ["Method"] + [n for _, n in KINDS]), ""]

    # ---- Table 10b: IBA against each reduction
    out += ["## Table 10b. IBA against each reduction of the same factors", ""]
    for name, P, freq in samples:
        rows = [[f"{la} vs {lb}"] + [entry(P, a, b, k, freq) for k, _ in KINDS] for la, a in (("Interpretable", FIXED), ("Accuracy", ACC)) for lb, b in METHODS[2:10]]
        out += [f"**{name}**", "", md_table(rows, ["Comparison"] + [n for _, n in KINDS]), ""]

    # ---- Table 11: volatility by horizon
    out += ["## Table 11. Volatility by horizon: relative difference in squared error against HAR, with the 95 % interval", ""]
    for name, P, freq in samples:
        g = P[(P.kind == "logrv") & (P.b == "REF") & (P.frequency == freq)]
        if g.empty:
            continue
        rows = []
        for lab, c in METHODS:
            x = g[g.a == c].sort_values("task", key=lambda s: s.str.extract(r"_h(\d+)$")[0].astype(int))
            if len(x):
                rows.append([lab] + [f"{100 * r.rel_diff:+.1f} % ({100 * r.ci_low:+.1f} to {100 * r.ci_high:+.1f})" for r in x.itertuples()])
        hs = sorted(g.task.unique(), key=lambda t: int(t.rsplit("_h", 1)[1]))
        out += [f"**{name}**", "", md_table(rows, ["Method"] + [f"{t.rsplit('_h', 1)[1]} weeks" if t.rsplit("_h", 1)[1] != "1" else "1 week" for t in hs]), ""]

    # ---- Table 12: formula content (development: the wrap-up report; confirmation: generic and random only)
    Wp = pd.read_csv(RES(study.WRAPUP, "paired_tests_priors.csv"))
    Wp["verdict"] = np.where(Wp.ci_high < 0, "better", np.where(Wp.ci_low > 0, "worse", "n.s."))
    rows = [[lab] + [entry(Wp, a, b, k) for k, _ in KINDS] for lab, a, b in (
        ("Elicited (K consensus) vs generic", "Kc|lin", "G|lin"), ("Elicited (S consensus) vs generic", "Sc|lin", "G|lin"), ("S consensus vs K consensus", "Sc|lin", "Kc|lin"),
        ("K consensus vs random", "Kc|lin", "Rm"), ("S consensus vs random", "Sc|lin", "Rm"), ("Generic vs random", "G|lin", "Rm"),
        ("Average of five K draws vs K consensus", "K@5", "Kc|lin"), ("Average of five S draws vs S consensus", "S@5", "Sc|lin"))]
    out += ["## Table 12. What the content of the formulas contributes", "", "**Development (weekly and monthly, 18 tasks)**", "",
            md_table(rows, ["Comparison"] + [n for _, n in KINDS]), ""]
    sp = pd.read_csv(RES(study.WRAPUP, "draw_spread.csv")).groupby("kind")[["sd K draws", "sd S draws", "sd R draws", "mean S - mean K"]].mean().mul(100).round(2)
    out += ["Spread across the five draws of a procedure (standard deviation of the loss, % of the loss of the generic formulas) and difference between procedures:", "",
            sp.reindex([k for k, _ in KINDS]).reset_index().to_markdown(index=False), ""]
    if Pc is not None:
        rows = [[lab] + [entry(Pc, a, b, k) for k, _ in KINDS] for lab, a, b in (("Elicited (K consensus) vs generic", FIXED, "G|lin"), ("K consensus vs random", FIXED, "Rm"))]
        out += ["**Confirmation (weekly, 10 tasks)**", "", md_table(rows, ["Comparison"] + [n for _, n in KINDS]), ""]
    if Ph is not None:
        rows = [[lab] + [entry(Ph, a, b, k) for k, _ in KINDS] for lab, a, b in (("Elicited (K consensus) vs generic", FIXED, "G|lin"), ("K consensus vs random", FIXED, "Rm"))]
        out += ["**Confirmation (monthly hedge-fund indices, 8 tasks)**", "", md_table(rows, ["Comparison"] + [n for _, n in KINDS]), ""]

    # ---- Table 13: estimators
    out += ["## Table 13. Tree ensembles against the linear model on the same features", ""]
    for name, P, freq in samples:
        rows = [[f"{lab} + {en}"] + [entry(P, f"{x}|{e}", f"{x}|lin", k, freq) for k, _ in KINDS]
                for x, lab in (("Kc", "IBA"), ("raw", "Raw factors"), ("gpca", "Group PCA")) for e, en in (("xgb", "XGBoost"), ("gbt", "LightGBM"))]
        out += [f"**{name}**", "", md_table(rows, ["Features + estimator"] + [n for _, n in KINDS]), ""]

    # ---- Tables 14-16 and the crisis table: the domain measures
    for name, d in (("Development", RES("extra-metrics-development")), ("Confirmation", RES(study.CONFIRM, "extra"))):
        if not os.path.exists(os.path.join(d, "var_backtest.csv")):
            continue
        V, S, T = (pd.read_csv(os.path.join(d, f)) for f in ("var_backtest.csv", "long_flat_rule.csv", "tail_classification.csv"))
        keep = ["IBA, K formulas (fixed)", "IBA, K formulas (averaged)", "group PCA", "PCA", "raw factors", "kernel PCA", "autoencoder", "HAR", "GARCH", "GJR-GARCH"]
        v = V[V.method.isin(keep)].copy()
        v["cell"] = [f"{100 * a:+.1f} %{' *' if t in ('better', 'worse') else ''}" for a, t in zip(v.tick_rel_to_har, v.tick_verdict.fillna(""))]
        t14 = v.pivot_table(index="method", columns=["alpha", "h"], values="cell", aggfunc="first").reindex([m for m in keep if m in set(v.method)])
        t14.columns = [f"{int(100 * a)} % VaR, {h} w" for a, h in t14.columns]
        vio = v[v.h == 1].pivot_table(index="method", columns="alpha", values="violation_rate").mul(100).round(2)
        t14["violations at 5 % / 1 % (1 w)"] = [f"{vio.loc[m, 0.05]:.2f} / {vio.loc[m, 0.01]:.2f} %" if m in vio.index else "" for m in t14.index]
        out += [f"## Table 14 ({name}). Value at risk from the volatility forecasts: quantile loss against HAR (* = interval excludes zero)", "", t14.reset_index().to_markdown(index=False), ""]
        v1 = v[v.h == 1].set_index(["method", "alpha"])
        rows = []
        for m in [m for m in keep if m in set(v.method)]:
            r = [m]
            for a in (0.05, 0.01):
                x = v1.loc[(m, a)]
                r += [f"{x.fz0_diff_to_har:+.3f}{' *' if x.fz0_verdict in ('better', 'worse') else ''}", f"{x.shortfall_ratio:.2f}", f"{100 * x.kupiec_reject:.0f} % / {100 * x.christoffersen_reject:.0f} %"]
            rows.append(r)
        out += [f"## Table 14b ({name}). One-week value at risk and expected shortfall: joint loss, shortfall and tests", "",
                md_table(rows, ["method"] + [f"{lv}: {c}" for lv in ("5 %", "1 %") for c in ("joint VaR-ES loss minus HAR's (* = interval excludes zero)", "realised / implied shortfall",
                                                                                         "series rejecting coverage / independence")]), ""]
        keep_s = ["IBA, K formulas (fixed)", "IBA, K formulas (averaged)", "group PCA", "PCA", "raw factors", "kernel PCA", "autoencoder", "historical mean", "trailing momentum", "buy-and-hold"]
        s = S[(S.frequency == "weekly") & S.method.isin(keep_s)]
        rows = []
        for m in keep_s:
            x = s[s.method == m].set_index("h")
            if len(x):
                r1 = x.loc[1]
                rows.append([m, " / ".join(f"{x.loc[h, 'sharpe']:.2f}" for h in sorted(x.index)), f"{r1.sharpe_10bp:.2f}", f"{100 * r1.max_drawdown:.0f} %", f"{100 * r1.cvar5:.1f} %", f"{100 * r1.invested:.0f} %",
                             "" if m == "buy-and-hold" else f"{int(r1.series_sharpe_above_bh)} / {int(r1.series_sharpe_10bp_above_bh)} / {int(r1.series_drawdown_below_bh)} of {int(r1.series)}"])
        out += [f"## Table 15 ({name}). Timing rule on weekly return forecasts", "",
                md_table(rows, ["Method", "Sharpe at 1 / 4 / 13 weeks", "Sharpe at 1 week after 10 bp per switch", "Max drawdown (1 w)", "5 % CVaR (1 w)", "Time invested (1 w)",
                                "Series with higher Sharpe / higher after costs / smaller drawdown than buy-and-hold (1 w)"]), ""]
        keep_t = ["IBA, K formulas (fixed)", "IBA, K formulas (averaged)", "group PCA", "PCA", "raw factors", "kernel PCA", "autoencoder", "volatility-based logit", "GARCH-based probability"]
        rows = []
        for m in keep_t:
            r = [m]
            for kind in ("tail_loss", "tail_gain"):
                x = T[(T.kind == kind) & (T.method == m) & (T.frequency == "weekly")]
                if x.empty:
                    r += ["–", "–", "–"]; continue
                tp, fp, fn, tn = (x[k].sum() for k in ("tp", "fp", "fn", "tn"))
                r += [f"{100 * tp / (tp + fp):.1f} % / {100 * tp / (tp + fn):.0f} %" if tp + fp else "no signal", f"{em.F.mcc(tp, fp, fn, tn):.3f}",
                      f"{1000 * x.reliability.mean():.2f} / {1000 * x.resolution.mean():.2f}"]
            rows.append(r)
        out += [f"## Table 16 ({name}). Tail probabilities as a classifier, weekly series (signal: probability above the base rate)", "",
                md_table(rows, ["Method"] + [f"{k}: {c}" for k in ("Large loss", "Large gain") for c in ("precision / recall", "MCC", "reliability / resolution of the Brier score, ×1000 (mean over tasks)")]), ""]
        X = pd.read_csv(os.path.join(d, "stress_periods.csv"))
        x = X[(X.frequency == "weekly") & X.method.isin(keep_t[:7] + ["GARCH"])]
        for kind, kn in (("logrv", "volatility (against HAR)"), ("return", "return (against the historical mean)")):
            t = x[x.kind == kind].pivot_table(index="method", columns="period", values="rel_to_reference", aggfunc="mean")
            t = t.reindex([m for m in keep_t[:7] + ["GARCH"] if m in t.index])[[p for p in dict.fromkeys(x.period)]].map(lambda v: "" if v != v else f"{100 * v:+.1f} %")
            out += [f"## Table A-crisis ({name}). Loss relative to the reference in crisis and drawdown periods: {kn}", "", t.reset_index().to_markdown(index=False), ""]

    # ---- Table 17: structure search (development)
    U = pd.read_csv(RES(study.WRAPUP, "search_units.csv"))
    g = U.groupby("algorithm")[["inner_gain", "clean_gain", "passes"]].mean().mul(100).round(1).reindex(["ABC", "GA", "PSO", "SA", "DE"])
    rows = [[a, f"{r.inner_gain:+.1f} %", f"{r.clean_gain:+.1f} %", f"{r.passes:.0f} %"] for a, r in g.iterrows()]
    F1 = pd.read_csv(RES(study.FIRST_SPEC, "paired_tests.csv"))
    F1["verdict"] = np.where(F1.ci_high < 0, "better", np.where(F1.ci_low > 0, "worse", "n.s."))
    ex = [[lab] + [entry(F1, a, "iba_e1|lin", k) for k, _ in KINDS] for lab, a in (("Exhaustive search over atoms vs fixed formula", "iba_x|lin"), ("Exhaustive low-order search vs fixed formula", "iba_xlo|lin"))]
    Ws = pd.read_csv(RES(study.WRAPUP, "paired_tests_search.csv"))
    Ws["verdict"] = np.where(Ws.ci_high < 0, "better", np.where(Ws.ci_low > 0, "worse", "n.s."))
    ex += [[lab] + [entry(Ws, a, b, k) for k, _ in KINDS] for lab, a, b in (("ABC, untested winner vs fixed formula", "iba_ca_r|lin", "Kc|lin"), ("ABC, tested winner vs fixed formula", "iba_ca|lin", "Kc|lin"),
                                                                     ("ABC colony ensemble vs fixed formula", "iba_ca_b", "Kc|lin"), ("ABC colony ensemble vs averaging without search", "iba_ca_b", "Kc_nb"))]
    ex = [r for r in ex if any(x != "–" for x in r[1:])]
    out += ["## Table 17. Structure search (development series)", "", "Five algorithms at equal budget on the pooled fitness (352 search problems per algorithm: asset class × task × re-selection date, three seeds each, seeds averaged):", "",
            md_table(rows, ["Algorithm", "Gain on the selection folds", "Gain on unused rows", "Winners passing the acceptance test"]), "",
            "Forecasts from searched formulas (exhaustive search: first study, generic formulas as the fixed formula):", "", md_table(ex, ["Comparison"] + [n for _, n in KINDS]), ""]

    # ---- Table 18: what the fitted models rely on (development, weekly, from the explanation step's traces)
    cells = [pickle.load(open(p, "rb")) for p in glob.glob(os.path.join(wr.REPO, "artifacts", "explain", "Kc", "cells_iba_ca_b", "weekly", "*", "*.pkl"))]
    if cells:
        names = {"IR": "Interest rates", "B": "Credit", "V": "Volatility", "AP": "Equity factors", "ST": "Styles", "FX": "Currencies", "COM": "Commodities",
                 "MC": "Macro-financial conditions", "ENDG": "Own behaviour"}
        rows = []
        for g, gn in names.items():
            r = [gn]
            for k, _ in KINDS:
                sh, pos = [], []
                for c in [c for c in cells if c["kind"] == k and g in c["groups"]]:
                    j = c["groups"].index(g); tot = np.abs(c["contrib"]).sum(axis=1)
                    sh.append((np.abs(c["contrib"][:, j])[tot > 0] / tot[tot > 0]).mean()); pos.append((c["coef"][:, j] > 0).mean())
                r.append(f"{100 * np.mean(sh):.0f} % ({100 * np.mean(pos):.0f} % +)" if sh else "–")
            rows.append(r)
        out += ["## Table 18. Share of the forecast's movement carried by each group, and share of fitted coefficients that are positive (weekly development series, interpretable reading)", "",
                md_table(rows, ["Group"] + [n for _, n in KINDS]), ""]

    # ---- Table D1 rows from the ablation run
    ab = RES("SPEC-2026-11-15-ablations", "paired_tests.csv")
    if os.path.exists(ab):
        A = pd.read_csv(ab)
        A["verdict"] = np.where(A.ci_high < 0, "better", np.where(A.ci_low > 0, "worse", "n.s."))
        gn = {"IR": "interest rates", "B": "credit", "V": "volatility", "AP": "equity factors", "TF": "trend-following", "ST": "styles", "FX": "currencies", "COM": "commodities",
              "MC": "macro-financial conditions", "ENDG": "own behaviour"}
        for freq in ("weekly", "monthly"):
            rows = [[f"without {gn[g]}"] + [entry(A, f"abl_wo_{g}|lin", "abl_base|lin", k, freq) for k, _ in KINDS] for g in gn if len(A[(A.a == f"abl_wo_{g}|lin") & (A.frequency == freq)])]
            rows += [[lab] + [entry(A, a, "abl_base|lin", k, freq) for k, _ in KINDS] for lab, a in (("one literal per group", "abl_one|lin"), ("distribution-based scaling", "abl_ecdf|lin"), ("no HAR stage", "abl_nohar|lin"))]
            out += [f"## Table D1 ({freq}, development). One component changed, against the unchanged interpretable reading (positive = the component contributes)", "",
                    md_table(rows, ["Change"] + [n for _, n in KINDS]), ""]
    # ---- Table F5: the secondary losses the engine stored with every confirmation forecast (descriptive: series means, no test)
    files = glob.glob(os.path.join(wr.REPO, "artifacts", study.CONFIRM, "stage11", "prior_*", "weekly", "*", "*", "metrics.csv")) if bc is not None else []
    if files:
        M = pd.concat([pd.read_csv(f).assign(prior=f.split(os.sep)[-5]) for f in files], ignore_index=True)
        M["kind"] = M.task.str.replace(r"(_q10)?_h\d+$", "", regex=True); M["h"] = M.task.str.extract(r"_h(\d+)$")[0].astype(int)
        where = [("IBA, interpretable reading", "prior_Kc", "iba_e1|lin"), ("IBA, generic formulas", "prior_G", "iba_e1|lin")]
        where += [(lab, "prior_G", c) for lab, c in METHODS[4:10]] + [("GARCH(1,1) / GARCH probability", "prior_G", ("bench|garch", "bench|garch_prob")),
                                                                   ("Volatility logit", "prior_G", ("", "bench|logit_vol")), ("HAR / base rate", "prior_G", ("bench|har", "bench|base"))]
        mean = lambda prior, c, kind, col: M[(M.prior == prior) & (M.config == c) & (M.kind == kind)].groupby("h")[col].mean()     # per horizon, mean over the 21 series
        ref = {"logrv": mean("prior_G", "bench|har", "logrv", "qlike"), "tail_loss": mean("prior_G", "bench|base", "tail_loss", "logloss"),
               "tail_gain": mean("prior_G", "bench|base", "tail_gain", "logloss")}
        rows = []
        for lab, prior, c in where:
            cv, ct = c if isinstance(c, tuple) else (c, c)
            q = mean(prior, cv, "logrv", "qlike")
            r = [lab] + [f"{100 * (q[h] / ref['logrv'][h] - 1):+.1f} %" if h in q.index else "–" for h in (1, 4, 13)]
            for kind in ("tail_loss", "tail_gain"):
                ll, auc, ece = (mean(prior, ct, kind, col) for col in ("logloss", "auc", "ece"))
                r += [f"{100 * (ll / ref[kind] - 1).mean():+.1f} %", f"{auc.mean():.3f}", f"{100 * ece.mean():.1f} %"] if len(ll) else ["–"] * 3
            rows.append(r)
        out += ["## Table F5. Secondary losses on the confirmation series (means over the 21 series; descriptive, no test)", "",
                md_table(rows, ["Method", "QLIKE vs HAR, 1 w", "QLIKE vs HAR, 4 w", "QLIKE vs HAR, 13 w", "Large loss: log score vs base rate", "Large loss: AUC",
                                "Large loss: calibration error", "Large gain: log score vs base rate", "Large gain: AUC", "Large gain: calibration error"]), ""]
